/**
 * Keeps the `@source` block of every app Tailwind entry (apps/<app>/src/styles.css) in sync
 * with the Nx project graph: the app sources plus the workspace libraries it depends on
 * (transitively). Tailwind 3 did this at build time with `createGlobPatternsForDependencies`;
 * Tailwind 4 reads static `@source` directives, so they are generated here.
 *
 * Usage:
 *   node tools/scripts/sync-tailwind-sources.mjs          # rewrite the blocks
 *   node tools/scripts/sync-tailwind-sources.mjs --check  # exit 1 when a block is stale (CI)
 */
import { execSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../..",
);
const START =
  "/* @sources:start - generated by tools/scripts/sync-tailwind-sources.mjs, do not edit */";
const END = "/* @sources:end */";
const SOURCE_ROOTS = ["libs/"];
const check = process.argv.includes("--check");

const graphFile = path.join(os.tmpdir(), `nx-graph-${process.pid}.json`);
execSync(`npx nx graph --file="${graphFile}"`, { cwd: ROOT, stdio: "ignore" });
const { nodes, dependencies } = JSON.parse(
  fs.readFileSync(graphFile, "utf8"),
).graph;
fs.rmSync(graphFile, { force: true });

function dependenciesOf(project, seen = new Set()) {
  for (const { target } of dependencies[project] ?? []) {
    if (nodes[target] && !seen.has(target)) {
      seen.add(target);
      dependenciesOf(target, seen);
    }
  }

  return seen;
}

let stale = 0;

for (const [name, node] of Object.entries(nodes)) {
  const entry = path.join(ROOT, node.data.root, "src/styles.css");

  if (node.type !== "app" || !fs.existsSync(entry)) {
    continue;
  }

  const libraries = [...dependenciesOf(name)]
    .map((project) => nodes[project].data.root)
    .filter((root) => SOURCE_ROOTS.some((prefix) => root.startsWith(prefix)))
    .sort();
  const toRoot = path
    .relative(path.dirname(entry), ROOT)
    .split(path.sep)
    .join("/");
  const block = [
    START,
    '@source "../";',
    ...libraries.map((root) => `@source "${toRoot}/${root}";`),
    END,
  ];

  const text = fs.readFileSync(entry, "utf8");
  const eol = text.includes("\r\n") ? "\r\n" : "\n";
  const start = text.indexOf(START);
  const end = text.indexOf(END);

  if (start < 0 || end < start) {
    throw new Error(
      `${path.relative(ROOT, entry)}: missing the @sources:start/@sources:end markers`,
    );
  }

  const updated = `${text.slice(0, start)}${block.join(eol)}${text.slice(end + END.length)}`;

  if (updated === text) {
    continue;
  }

  stale++;

  if (check) {
    console.error(`stale: ${path.relative(ROOT, entry)}`);
  } else {
    fs.writeFileSync(entry, updated);
    console.log(
      `updated: ${path.relative(ROOT, entry)} (${libraries.length} libraries)`,
    );
  }
}

if (check && stale > 0) {
  process.exit(1);
}

console.log(
  stale === 0
    ? "Tailwind sources up to date"
    : `${stale} entries ${check ? "stale" : "updated"}`,
);
